begin;
do $$
declare
  dono uuid:=gen_random_uuid();gerente uuid:=gen_random_uuid();outro uuid:=gen_random_uuid();
  oficina uuid:=gen_random_uuid();externa uuid:=gen_random_uuid();produto uuid:=gen_random_uuid();
  foto text;foto_externa text;r public.produtos;n integer;rejeitado boolean;
begin
  insert into auth.users(id,email,raw_user_meta_data) values(dono,'inv-owner@example.com','{"full_name":"Dono estoque"}'),
    (gerente,'inv-manager@example.com','{}'),(outro,'inv-other@example.com','{}');
  insert into public.oficinas(id,dono_id,nome,status,trial_ends_at) values(oficina,dono,'Estoque teste','ativo',null),(externa,outro,'Externa','ativo',null);
  insert into public.oficina_usuarios(user_id,oficina_id,nome,email) values(gerente,oficina,'Gerente estoque','inv-manager@example.com');
  foto:=oficina::text||'/'||produto::text||'/'||gen_random_uuid()::text||'.png';
  foto_externa:=externa::text||'/'||gen_random_uuid()::text||'/'||gen_random_uuid()::text||'.png';
  insert into storage.objects(bucket_id,name) values('estoque-produtos',foto_externa);
  perform set_config('request.jwt.claim.sub',dono::text,true);
  execute 'set local role authenticated';
  insert into storage.objects(bucket_id,name) values('estoque-produtos',foto);
  select * into r from public.cadastrar_produto(oficina,produto,'Filtro','Aplicação teste',' abC123 ',20.50,5,1,foto);
  if r.quantidade<>5 or r.codigo_serie<>'ABC123' or r.foto_path<>foto or r.criado_por->>'perfil'<>'dono' then raise exception 'FAIL: invalid product creation';end if;
  if not exists(select 1 from public.estoque_movimentos where produto_id=produto and tipo='saldo_inicial' and saldo_antes=0 and saldo_depois=5) then raise exception 'FAIL: initial movement missing';end if;
  update public.produtos set preco=25,nome='Filtro editado' where id=produto;
  rejeitado:=false;
  begin update public.produtos set quantidade=100 where id=produto;exception when insufficient_privilege then rejeitado:=true;end;
  if not rejeitado then raise exception 'FAIL: balance can be bypassed';end if;
  rejeitado:=false;
  begin perform public.cadastrar_produto(oficina,gen_random_uuid(),'Duplicado','','abc123',0,0,0,null);exception when unique_violation then rejeitado:=true;end;
  if not rejeitado then raise exception 'FAIL: duplicate code accepted';end if;
  rejeitado:=false;
  begin update public.produtos set foto_path=foto_externa where id=produto;exception when others then rejeitado:=true;end;
  if not rejeitado then raise exception 'FAIL: photo from other workshop attached';end if;
  if exists(select 1 from storage.objects where name=foto_externa) then raise exception 'FAIL: foreign photo visible';end if;
  rejeitado:=false;
  begin insert into storage.objects(bucket_id,name) values('estoque-produtos',foto_externa||'2');exception when insufficient_privilege then rejeitado:=true;end;
  if not rejeitado then raise exception 'FAIL: foreign upload allowed';end if;
  perform set_config('request.jwt.claim.sub',gerente::text,true);
  select * into r from public.movimentar_estoque(produto,'entrada',2,'Compra de peças');
  if r.quantidade<>7 then raise exception 'FAIL: entry balance';end if;
  select * into r from public.movimentar_estoque(produto,'saida',3,'Uso na oficina');
  if r.quantidade<>4 then raise exception 'FAIL: exit balance';end if;
  select * into r from public.movimentar_estoque(produto,'ajuste',1.5,'Contagem física');
  if r.quantidade<>1.5 or r.alterado_por->>'perfil'<>'gerente' then raise exception 'FAIL: adjustment or author';end if;
  select count(*) into n from public.estoque_movimentos where produto_id=produto;
  rejeitado:=false;
  begin perform public.movimentar_estoque(produto,'saida',2,'Saída acima do saldo');exception when others then rejeitado:=true;end;
  if not rejeitado or (select quantidade from public.produtos where id=produto)<>1.5 or (select count(*) from public.estoque_movimentos where produto_id=produto)<>n then raise exception 'FAIL: insufficient stock changed data';end if;
  rejeitado:=false;
  begin perform public.movimentar_estoque(produto,'entrada',0.0001,'Fração inválida');exception when others then rejeitado:=true;end;
  if not rejeitado then raise exception 'FAIL: excessive precision';end if;
  rejeitado:=false;
  begin insert into public.estoque_movimentos(oficina_id,produto_id,tipo,quantidade,saldo_antes,saldo_depois,motivo)
    values(oficina,produto,'entrada',99,1.5,100.5,'Forjado');exception when insufficient_privilege then rejeitado:=true;end;
  if not rejeitado then raise exception 'FAIL: history forged';end if;
  perform public.movimentar_estoque(produto,'saida',1,'Primeira saída');
  rejeitado:=false;
  begin perform public.movimentar_estoque(produto,'saida',1,'Segunda saída');exception when others then rejeitado:=true;end;
  if not rejeitado or (select quantidade from public.produtos where id=produto)<>0.5 then raise exception 'FAIL: overselling';end if;
  if not exists(select 1 from public.estoque_movimentos where produto_id=produto and criado_por->>'nome'='Gerente estoque') then raise exception 'FAIL: manager not recorded';end if;
  perform set_config('request.jwt.claim.sub',outro::text,true);
  if exists(select 1 from public.produtos where id=produto) or exists(select 1 from public.estoque_movimentos where produto_id=produto) then raise exception 'FAIL: other workshop reads inventory';end if;
  select * into r from public.cadastrar_produto(externa,gen_random_uuid(),'Outro filtro','','ABC123',10,1,0,null);
  if r.codigo_serie<>'ABC123' then raise exception 'FAIL: code not scoped by workshop';end if;
  rejeitado:=false;
  begin perform public.movimentar_estoque(produto,'saida',0.5,'Acesso indevido');exception when insufficient_privilege then rejeitado:=true;end;
  if not rejeitado then raise exception 'FAIL: other workshop modifies stock';end if;
  perform set_config('request.jwt.claim.sub',dono::text,true);
  update public.oficina_usuarios set ativo=false where user_id=gerente;
  perform set_config('request.jwt.claim.sub',gerente::text,true);
  if exists(select 1 from public.produtos) or exists(select 1 from storage.objects where name=foto) then raise exception 'FAIL: revoked manager reads stock/photos';end if;
  execute 'reset role';
end;
$$;
rollback;
